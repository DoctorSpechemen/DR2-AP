"""Writes the plugin's Tables.h from the world's Data.py, so the two can never disagree about a name.

Usage: python3 gen_tables.py <path to apworld/dr2/Data.py> <path to plugin/Tables.h>
"""
import importlib.util
import sys


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(data_path: str, out_path: str) -> None:
    spec = importlib.util.spec_from_file_location("dr2_data", data_path)
    d = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(d)

    out = ["// Generated by tools/gen_tables.py from the world's Data.py. Do not edit by hand.", "",
           "struct ApTextCheck { int text_id; const char* location; };",
           "struct ApSurvivor { const char* internal_name; const char* location; };",
           "struct ApItem { const char* name; int kind; int value; };", "",
           "enum { kApItemMoney = 1, kApItemPP, kApItemZombrex, kApItemCaseGate, kApItemTrap };",
           "enum { kApTrapNaked = 1, kApTrapButterfingers, kApTrapAmbush, kApTrapWrongNumber, "
           "kApTrapSickness };", ""]

    out.append("// Story cases in order. A case is finished once its own \"Completed\" and the next entry's \"Activated\" were seen.")
    out.append("static const ApTextCheck kApCases[] = {")
    for name, text_id, _case in d.CASES:
        out.append(f"    {{ {text_id}, {c_string(name)} }},")
    out.append("};")
    out.append(f"static const int kApTheFactsTextId = {d.THE_FACTS_ID};")
    out.append(f"static const int kApOvertimeTextId = {d.OVERTIME_ID};")
    out.append(f"static const char* const kApTheFactsLocation = {c_string(d.THE_FACTS)};")
    out.append("")
    out.append("static const ApTextCheck kApPsychopaths[] = {")
    for title, text_id, _start in d.PSYCHOPATHS:
        out.append(f"    {{ {text_id}, {c_string(d.psychopath_location(title))} }},")
    out.append("};")
    out.append("")
    out.append("// Checks sent when a mission reaches state 2 (finished). kind: 1 = case, 2 = psychopath.")
    out.append("struct ApMissionCheck { const char* mission; const char* location; int kind; };")
    out.append("static const ApMissionCheck kApMissionChecks[] = {")
    for name, _text_id, _case in d.CASES:
        out.append(f"    {{ {c_string(d.CASE_MISSIONS[name])}, {c_string(name)}, 1 }},")
    for title, _text_id, _start in d.PSYCHOPATHS:
        out.append(f"    {{ {c_string(d.PSYCHOPATH_MISSIONS[title])}, {c_string(d.psychopath_location(title))}, 2 }},")
    out.append("};")
    out.append(f"static const char* const kApTheFactsMission = {c_string(d.THE_FACTS_MISSION)};")
    out.append(f"static const char* const kApOvertimeMission = {c_string(d.OVERTIME_MISSION)};")
    out.append("")
    out.append("static const ApSurvivor kApSurvivors[] = {")
    for internal, full_name, _mission, _start in d.SURVIVORS:
        out.append(f"    {{ {c_string(internal)}, {c_string(d.survivor_location(full_name))} }},")
    out.append("};")
    out.append("")
    out.append("// Counters in the mod's mission that go off when a poster is examined (tools/build_ap_mission.py).")
    out.append("struct ApCounterCheck { const char* counter; const char* location; };")
    out.append("static const ApCounterCheck kApCounterChecks[] = {")
    for event, name in d.MOVIE_POSTERS:
        out.append(f"    {{ {c_string('AP_Poster_' + event.split('_', 1)[1])}, {c_string(d.poster_location(name))} }},")
    out.append("};")
    out.append("")
    out.append("static const int kApKillMilestones[] = { " + ", ".join(str(k) for k in d.KILL_MILESTONES) + " };")
    out.append("static const char* const kApKillLocations[] = {")
    for kills in d.KILL_MILESTONES:
        out.append(f"    {c_string(d.kill_location(kills))},")
    out.append("};")
    out.append(f"static const int kApMaxLevel = {d.MAX_LEVEL};            // locations: \"Reach Level <n>\", n from 2")
    out.append(f"static const int kApMaxKateyGifts = {d.MAX_KATEY_GIFTS};       // locations: \"Katey's Gift <n>\", n from 1")
    out.append(f"static const int kApMaxZombrexChecks = {d.MAX_ZOMBREX_CHECKS};     // locations: \"Zombrex Found <n>\", n from 1")
    out.append(f"static const int kApZombrexKeyItem = {d.ZOMBREX_KEY_ITEM_ID};")
    out.append("")
    traps = {d.NAKED_TRAP: "kApTrapNaked", d.BUTTERFINGERS_TRAP: "kApTrapButterfingers", d.AMBUSH_TRAP: "kApTrapAmbush",
             d.WRONG_NUMBER_TRAP: "kApTrapWrongNumber", d.SICKNESS_TRAP: "kApTrapSickness"}
    assert set(traps) == set(d.TRAPS), "a trap was added to Data.py but not to gen_tables.py"
    out.append("static const ApItem kApItems[] = {")
    for case, name in d.CASE_GATE_ITEMS.items():
        out.append(f"    {{ {c_string(name)}, kApItemCaseGate, {case} }},")
    out.append(f"    {{ {c_string(d.ZOMBREX_ITEM)}, kApItemZombrex, 1 }},")
    for name, amount in d.MONEY_FILLERS.items():
        out.append(f"    {{ {c_string(name)}, kApItemMoney, {amount} }},")
    for name, amount in d.PP_FILLERS.items():
        out.append(f"    {{ {c_string(name)}, kApItemPP, {amount} }},")
    for name in d.TRAPS:
        out.append(f"    {{ {c_string(name)}, kApItemTrap, {traps[name]} }},")
    out.append("};")
    out.append("")

    with open(out_path, "w", encoding="ascii", newline="\r\n") as f:
        f.write("\n".join(out))
    print(f"wrote {out_path}: {len(d.CASES)} cases, {len(d.PSYCHOPATHS)} psychopaths, {len(d.SURVIVORS)} survivors")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
